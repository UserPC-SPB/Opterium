    #[test]
    fn dry_run_and_no_skills_stay_within_their_scope() {
        let repo = Repo::tiny("release_scope", VERSION);
        for index in 0..SKILLS.len() {
            repo.add_skill(index, &skill_md("0.9.0"));
        }
        let before = repo.snapshot();

        let dry = repo.release(&["-DryRun"]);
        dry.assert_ok();
        dry.assert_mentions("DRY RUN: nothing was built, copied or modified.");
        dry.assert_mentions("2. cargo test --locked");
        dry.assert_mentions("3. cargo build --release --locked");
        assert!(!release_line(&dry.output, "msvc       : ").is_empty());
        let mut destinations = vec!["dist/any_txt_parser.exe".to_string(), "dist/HELP.md".into()];
        for (root, exe) in SKILLS {
            destinations.push(format!("{root}/{exe}"));
            destinations.push(format!("{root}/references/parser.md"));
            destinations.push(format!("{root}/SKILL.md  (now: 0.9.0)"));
        }
        for destination in &destinations {
            dry.assert_mentions(&windows_path(destination));
        }
        assert!(repo.snapshot() == before, "a dry run must not write");

        let dry_dist_only = repo.release(&["-DryRun", "-NoSkills"]);
        dry_dist_only.assert_ok();
        dry_dist_only.assert_mentions(r"dist\HELP.md");
        assert!(!dry_dist_only.output.contains(r".dsh\"));
        assert!(repo.snapshot() == before, "a dry run must not write");

        let dist_only = repo.release(&["-NoSkills", "-SkipTests", "-SkipBuild", "-ExePath", BIN]);
        dist_only.assert_ok();
        // The tiny crate's sources were written after the test binary was built.
        dist_only.assert_mentions("WARNING: prebuilt exe is older than");
        dist_only.assert_mentions("skill folders not touched (-NoSkills)");
        assert!(repo.read("dist/any_txt_parser.exe") == std::fs::read(BIN).unwrap());
        assert!(repo.read("dist/HELP.md") == repo.read("HELP.md"));
        let after = repo.snapshot();
        for (path, bytes) in &before {
            assert!(after.get(path) == Some(bytes), "{} changed", path.display());
        }
    }

    #[test]
    fn version_disagreement_stops_the_release_before_anything_is_written() {
        let cases: [(&str, Repo, String); 4] = [
            (
                "lib.rs vs Cargo.toml",
                Repo::tiny_with("release_lib_mismatch", VERSION, "9.0.0"),
                format!(
                    "version mismatch: src\\lib.rs PARSER_VERSION = {VERSION}, Cargo.toml [package] version = 9.0.0"
                ),
            ),
            (
                "Cargo.lock",
                {
                    let repo = Repo::tiny("release_lock_mismatch", VERSION);
                    let lock = repo.read_string("Cargo.lock");
                    repo.write(
                        "Cargo.lock",
                        lock.replace(&format!("version = \"{VERSION}\""), "version = \"0.0.1\""),
                    );
                    repo
                },
                format!(
                    "version mismatch: Cargo.lock any_txt_parser = 0.0.1, Cargo.toml [package] version = {VERSION}"
                ),
            ),
            (
                "HELP.md title",
                {
                    let repo = Repo::tiny("release_help_mismatch", VERSION);
                    repo.write("HELP.md", help_md("0.0.1"));
                    repo
                },
                format!(
                    "HELP.md title names v0.0.1 but the release version is {VERSION} - update HELP.md first"
                ),
            ),
            (
                "stale prebuilt exe",
                Repo::tiny("release_stale_exe", "9.9.9"),
                format!(
                    "--version printed 'any_txt_parser {VERSION}', expected 'any_txt_parser 9.9.9' (stale or foreign binary)"
                ),
            ),
        ];
        for (case, repo, message) in cases {
            repo.add_skill(0, &skill_md("0.9.0"));
            let before = repo.snapshot();
            let outcome = repo.release(&PREBUILT);
            outcome.assert_failed_with(&message);
            assert!(repo.snapshot() == before, "{case}: nothing may be written");
        }
    }

    #[test]
    fn bad_layout_arguments_or_formatting_stop_the_release() {
        let repo = Repo::tiny("release_no_mention", VERSION);
        repo.add_skill(0, &skill_md("0.9.0"));
        repo.add_skill(
            1,
            "---\nname: any-txt-parser\n---\nNo parser version here.\n",
        );
        let before = repo.snapshot();
        repo.release(&PREBUILT).assert_failed_with(
            r".pi\skills\any-txt-parser\SKILL.md has no 'any_txt_parser X.Y.Z' version mention to update",
        );
        assert!(repo.snapshot() == before, "nothing may be written");

        let repo = Repo::tiny("release_exe_path_alone", VERSION);
        let before = repo.snapshot();
        repo.release(&["-ExePath", BIN])
            .assert_failed_with("-ExePath requires -SkipBuild");
        let unknown = repo.release(&["-NoSuchOption"]);
        assert_ne!(
            unknown.code, 0,
            "unknown option must fail:\n{}",
            unknown.output
        );
        assert!(repo.snapshot() == before, "nothing may be written");

        let repo = Repo::tiny("release_unformatted", VERSION);
        repo.write(
            "src/lib.rs",
            format!("pub const PARSER_VERSION:&str=\"{VERSION}\";\n"),
        );
        repo.add_skill(0, &skill_md("0.9.0"));
        let before = repo.snapshot();
        repo.release(&PREBUILT)
            .assert_failed_with("cargo fmt --check failed with exit code 1");
        assert!(repo.snapshot() == before, "nothing may be published");
    }

