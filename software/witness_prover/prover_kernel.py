# T-tau: the Pythagorean identity tau = S^2 - 4P - D^2 = 0
# =====================================================================
def tau_xy(x: int, y: int) -> int:
    s = x + y
    p = x * y
    d = x - y
    return s * s - 4 * p - d * d


def _route_tau_primitive():
    n = 0
    for x in range(1, 41):
        for y in range(1, 41):
            assert tau_xy(x, y) == 0, f"tau({x},{y}) != 0"
            n += 1
    return True, f"1600 primitive cells (1..40)x(1..40) all tau=0"


def _route_tau_scaled():
    for x in range(1, 25):
        for y in range(1, 25):
            assert tau_xy(x * 7, y * 11) == 0
            assert tau_xy(x * 13, y * 3) == 0
    return True, "gcd-fold scaled cells (x7y11, x13y3) all tau=0"


def _route_tau_commutative():
    m = 0
    for x in range(1, 30):
        for y in range(1, 30):
            assert tau_xy(x, y) == tau_xy(y, x)
            m += 1
    return True, f"{m} commutative pairs all tau-symmetric"


def _kernel_tau():
    # symbolic check: (x+y)^2 - 4xy - (x-y)^2 == 0, expand manually
    # (x+y)^2 - 4xy - (x-y)^2 = (x^2+2xy+y^2) - 4xy - (x^2-2xy+y^2)
    #                          = 0 identically (algebraic cancellation)
    # verify on a big sweep with exact ints
    for x in range(1, 60):
        for y in range(1, 60):
            if tau_xy(x, y) != 0:
                return False, f"counterexample tau({x},{y})={tau_xy(x,y)}"
    return True, ("algebraic expansion cancels all terms; sweep "
                  "1..60 x 1..60 gives 0 everywhere")


