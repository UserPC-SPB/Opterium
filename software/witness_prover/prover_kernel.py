def _route_tunnel_witness():
    i, j, k = 0, 6, 31
    ri, rj, rk = E8_ROOTS[i], E8_ROOTS[j], E8_ROOTS[k]
    vsum = tuple(ri[t] + rj[t] + rk[t] for t in range(8))
