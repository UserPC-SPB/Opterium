# T-e8-count: 240 roots = 112 D8 + 128 spinor, all ||r||^2 = 8
# =====================================================================
def generate_e8_roots():
    """First-principles generation (same construction rules as helpdoc.py)."""
    roots = []
    for i, j in combinations(range(8), 2):
        for si, sj in product((2, -2), repeat=2):
            v = [0] * 8
            v[i] = si
            v[j] = sj
            roots.append(tuple(v))
    for bits in range(256):
        if bin(bits).count("1") % 2 == 0:  # even parity
            v = tuple((1 if (bits >> k) & 1 else -1) for k in range(8))
            roots.append(v)
    return roots


E8_ROOTS = generate_e8_roots()


def dot8(a, b):
    return sum(ai * bi for ai, bi in zip(a, b))


def _route_e8_generators():
    n_d8 = 112
    n_sp = 128
    assert len(E8_ROOTS) == n_d8 + n_sp == 240
    return True, "240 roots generated by construction rules (112 D8 + 128 spinor)"


def _route_e8_norm():
    bad = [i for i, v in enumerate(E8_ROOTS) if sum(x * x for x in v) != 8]
    assert not bad, f"roots with norm^2 != 8: {bad[:5]}"
    return True, "all 240 generated roots satisfy ||r||^2 = 8"


def _route_e8_kinds():
    n_d8 = sum(1 for v in E8_ROOTS if max(abs(x) for x in v) == 2)
    n_sp = sum(1 for v in E8_ROOTS if max(abs(x) for x in v) == 1)
    assert n_d8 == 112 and n_sp == 128
    return True, "kind split by construction: D8(±2) count 112, spinor(±1) count 128"


def _kernel_e8():
    if len(E8_ROOTS) != 240:
        return False, f"count={len(E8_ROOTS)}"
    if any(sum(x * x for x in v) != 8 for v in E8_ROOTS):
        return False, "norm^2 != 8"
    nd = sum(1 for v in E8_ROOTS if max(abs(x) for x in v) == 2)
    ns = 240 - nd
    if nd != 112 or ns != 128:
        return False, f"D8={nd} spinor={ns}"
    return True, "240 roots, norm^2=8, 112 D8 + 128 spinor (recomputed)"


